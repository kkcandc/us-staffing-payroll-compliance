"""Merge generated + curated rows into the published dataset files.

Outputs:
  data/facts.csv            one row per fact (long format, the canonical table)
  data/facts.json           same rows plus dataset metadata
  data/states/XX.json       per-jurisdiction bundle (used by state pages and the API)
  data/compare.csv          wide table: one row per state, one column per core field (for compare view)
  COVERAGE.md               per state x field coverage matrix
Run: python3 pipeline/build.py
"""
import csv, glob, json, os
from collections import defaultdict
from common import FIELDS, JURISDICTIONS, CORE_FIELDS, DATA, ROOT, read_rows, write_rows

VERSION = "0.1.0-rc"
BUILT = "2026-11-24"

def load():
    rows = []
    cur = sorted(glob.glob(os.path.join(DATA, "curated", "*.csv")))
    overrides = [p for p in cur if os.path.basename(p).startswith("overrides_")]
    for p in sorted(glob.glob(os.path.join(DATA, "generated", "*.csv"))) + [p for p in cur if p not in overrides]:
        rows.extend(read_rows(p))
    # Reviewed corrections: rows in curated/overrides_*.csv replace the row with the same id, or add a new row.
    for p in overrides:
        idx = {r["id"]: i for i, r in enumerate(rows)}
        for o in read_rows(p):
            if o["id"] in idx:
                rows[idx[o["id"]]] = o
            else:
                rows.append(o)
    ids = defaultdict(int)
    for r in rows:
        ids[r["id"]] += 1
    dupes = [k for k, v in ids.items() if v > 1]
    if dupes:
        raise SystemExit(f"duplicate ids: {dupes[:10]}")
    order = {c: i for i, c in enumerate(["US"] + list(JURISDICTIONS))}
    rows.sort(key=lambda r: (order.get(r["jurisdiction"], 999), r["category"], r["field"], r["id"]))
    return rows

def main():
    rows = load()
    write_rows(os.path.join(DATA, "facts.csv"), rows)
    meta = {
        "name": "US Staffing Payroll Compliance Dataset",
        "version": VERSION, "built": BUILT, "license": "CC-BY-4.0",
        "publisher": "Catalyst Works", "homepage": "https://getcatalystworks.com/",
        "row_count": len(rows),
        "disclaimer": "Reference information compiled from official government sources. Not legal or tax advice. Check the cited source before relying on any value.",
    }
    with open(os.path.join(DATA, "facts.json"), "w", encoding="utf-8") as f:
        json.dump({"meta": meta, "facts": rows}, f, indent=1, ensure_ascii=False)
    by = defaultdict(list)
    for r in rows:
        by[r["jurisdiction"]].append(r)
    os.makedirs(os.path.join(DATA, "states"), exist_ok=True)
    for code, rs in by.items():
        name = JURISDICTIONS.get(code, rs[0]["jurisdiction_name"])
        with open(os.path.join(DATA, "states", f"{code}.json"), "w", encoding="utf-8") as f:
            json.dump({"meta": dict(meta, jurisdiction=code, jurisdiction_name=name, row_count=len(rs)), "facts": rs}, f, indent=1, ensure_ascii=False)
    # compare.csv
    cols = [f for _, f in CORE_FIELDS] + ["total_new_employer_rate", "pay_frequency_state_rule"]
    with open(os.path.join(DATA, "compare.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["jurisdiction", "jurisdiction_name"] + cols)
        for code, name in JURISDICTIONS.items():
            vals = {r["field"]: r["value"] for r in by.get(code, []) if r["status"] == "verified"}
            w.writerow([code, name] + [vals.get(c, "") for c in cols])
    # COVERAGE.md
    lines = ["# Coverage", "", f"Built {BUILT}, version {VERSION}. Generated by `pipeline/build.py`; do not edit by hand.", "",
             "Legend: `V` verified from an official source, `R` present but needs review, `-` blank (not yet verified; a blank is intentional, we never guess).", ""]
    hdr = [f for _, f in CORE_FIELDS]
    short = {"suta_taxable_wage_base": "UI wage base", "suta_new_employer_rate": "UI new rate", "suta_rate_range": "UI range",
             "futa_credit_reduction": "FUTA CR", "state_minimum_wage": "Min wage", "dol_payday_table": "Payday (DOL)",
             "final_pay_discharge": "Final pay fired", "final_pay_resignation": "Final pay quit", "wc_agency": "WC agency",
             "wc_monopolistic_state_fund": "WC state fund", "staffing_or_peo_registration": "Staffing reg", "new_hire_reporting_deadline": "New hire"}
    lines.append("| State | " + " | ".join(short[h] for h in hdr) + " | Verified |")
    lines.append("|---|" + "---|" * (len(hdr) + 1))
    field_tot = defaultdict(int)
    full = 0
    for code, name in JURISDICTIONS.items():
        st = {}
        for r in by.get(code, []):
            st[r["field"]] = "V" if r["status"] == "verified" and r["value"] else ("R" if r["value"] else "-")
        cells = [st.get(h, "-") for h in hdr]
        n = sum(c == "V" for c in cells)
        for h, c in zip(hdr, cells):
            field_tot[h] += c == "V"
        full += n == len(hdr)
        lines.append(f"| {code} | " + " | ".join(cells) + f" | {n}/{len(hdr)} |")
    lines += ["", "## Totals by field (verified jurisdictions out of 51)", ""]
    for h in hdr:
        lines.append(f"- {short[h]} (`{h}`): {field_tot[h]}/51")
    tot_v = sum(field_tot.values())
    lines += ["", f"Verified state x field cells: {tot_v}/{51 * len(hdr)} ({100 * tot_v / (51 * len(hdr)):.0f}%). Jurisdictions complete on all core fields: {full}/51.", "",
              "Extra field `total_new_employer_rate` (new-employer UI rate including mandatory surcharges, fund-building rates and assessments, where a state agency publishes it): " + ", ".join(sorted({r["jurisdiction"] for r in rows if r["field"] == "total_new_employer_rate" and r["status"] == "verified"})) + ".", "",
              "Federal (US) rows used by the calculator: " + str(len(by.get("US", []))) + ".", ""]
    open(os.path.join(ROOT, "COVERAGE.md"), "w", encoding="utf-8").write("\n".join(lines))
    print(f"rows={len(rows)} jurisdictions={len(by)} verified_cells={tot_v}/{51 * len(hdr)}")

if __name__ == "__main__":
    main()
